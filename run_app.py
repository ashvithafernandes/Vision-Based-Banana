import os
import sys
import time
import json
import urllib.request
import subprocess
import signal

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
EXPO_DIR = os.path.join(BASE_DIR, "carbide_detection_expo")
PYTHON_EXE = sys.executable
CONFIG_JS = os.path.join(EXPO_DIR, "src", "services", "config.js")

def kill_process(proc):
    if proc and proc.poll() is None:
        try:
            proc.terminate()
            proc.wait(timeout=2)
        except Exception:
            try:
                proc.kill()
            except Exception:
                pass

def get_ngrok_url(timeout=10):
    start = time.time()
    while time.time() - start < timeout:
        try:
            req = urllib.request.Request("http://127.0.0.1:4040/api/tunnels")
            with urllib.request.urlopen(req, timeout=2) as response:
                data = json.loads(response.read().decode())
                tunnels = data.get("tunnels", [])
                for t in tunnels:
                    url = t.get("public_url")
                    if url and url.startswith("https://"):
                        return url
        except Exception:
            pass
        time.sleep(0.5)
    return None

def main():
    print("==================================================================")
    print("  RipeScan / Banana Carbide Detection - Unified One-Click Launcher")
    print("==================================================================")
    
    server_proc = None
    ngrok_proc = None

    try:
        # 1. Start Two-Stage AI Server (in dedicated console for live logs)
        print("[1/3] Starting Two-Stage AI Server (Live Logs Console)...")
        server_py = os.path.join(BASE_DIR, "model_server.py")
        creationflags = subprocess.CREATE_NEW_CONSOLE if sys.platform == "win32" else 0
        server_proc = subprocess.Popen(
            [PYTHON_EXE, server_py],
            cwd=BASE_DIR,
            creationflags=creationflags,
        )
        time.sleep(1.5)

        # 2. Start Ngrok Tunnel on Port 5000
        print("[2/3] Initializing Ngrok Tunnel on port 5000...")
        ngrok_proc = subprocess.Popen(
            ["ngrok.exe", "http", "5000"],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )

        ngrok_url = get_ngrok_url(timeout=10)
        if ngrok_url:
            print(f"[✓] Ngrok Tunnel active: {ngrok_url}")
            server_url = f"{ngrok_url}/predict"
        else:
            print("[!] Warning: Could not retrieve Ngrok tunnel URL. Falling back to local LAN IP.")
            server_url = "http://192.168.1.5:5000/predict"

        # Update Expo config.js
        with open(CONFIG_JS, "w", encoding="utf-8") as f:
            f.write(f"// Auto-generated by run_app launcher\n")
            f.write(f"export const SERVER_URL = '{server_url}';\n")
        print(f"[✓] App configured to target AI endpoint: {server_url}")

        # 3. Launch Expo Dev Server with QR Code in foreground
        print("\n[3/3] Launching Expo SDK 58 Dev Server...")
        print("------------------------------------------------------------------")
        print("  Scan the QR code below using the Expo Go app on your phone:")
        print("------------------------------------------------------------------\n")

        npx_cmd = "npx.cmd" if sys.platform == "win32" else "npx"
        expo_proc = subprocess.Popen(
            [npx_cmd, "expo", "start", "-c"],
            cwd=EXPO_DIR,
        )
        expo_proc.wait()

    except KeyboardInterrupt:
        print("\n\nShutting down services...")
    finally:
        print("Stopping AI model server and ngrok tunnel...")
        kill_process(server_proc)
        kill_process(ngrok_proc)
        # Extra safety check for ngrok on Windows
        if sys.platform == "win32":
            subprocess.run(["taskkill", "/F", "/IM", "ngrok.exe"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        print("[✓] All services stopped cleanly. Goodbye!")

if __name__ == "__main__":
    main()

